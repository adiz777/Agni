"""
Pydantic Schemas for Safe AI Investigation Assistant (R3)
"""
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class AIProviderType(StrEnum):
    NONE = "none"
    OLLAMA = "ollama"
    OPENAI = "openai"
    OPENAI_COMPATIBLE = "openai_compatible"


class AIConfig(BaseModel):
    enabled: bool = False
    provider: str = AIProviderType.OLLAMA.value
    base_url: str = "http://127.0.0.1:11434"
    model: str = "llama3.2"
    api_key: str | None = None
    timeout_seconds: float = 12.0
    require_external_consent: bool = True
    consent_granted: bool = False


class AIStatusRead(BaseModel):
    enabled: bool
    provider: str
    base_url: str
    model: str
    api_key_configured: bool
    api_key_masked: str | None = None
    consent_granted: bool
    timeout_seconds: float
    is_external: bool

    model_config = ConfigDict(from_attributes=True)


class AIConfigUpdate(BaseModel):
    enabled: bool | None = None
    provider: str | None = None
    base_url: str | None = None
    model: str | None = None
    api_key: str | None = None
    consent_granted: bool | None = None
    timeout_seconds: float | None = None


class IncidentInvestigationRequest(BaseModel):
    incident_id: str
    include_correlated_events: bool = True
    max_events: int = Field(default=10, ge=1, le=50)
    user_notes: str | None = None
    consent_given: bool = False


class RedactionPreviewRequest(BaseModel):
    incident_id: str | None = None
    sample_text: str | None = None
    include_correlated_events: bool = True


class RedactionPreviewResponse(BaseModel):
    incident_id: str | None = None
    original_text_summary: str
    redacted_text_summary: str
    redacted_items_count: dict[str, int]
    target_endpoint: str
    is_external: bool


class AIInvestigationResponse(BaseModel):
    success: bool
    incident_id: str
    provider_used: str
    model_used: str
    analysis: str | None = None  # Markdown advisory text
    mitre_techniques: list[str] = Field(default_factory=list)
    investigation_steps: list[str] = Field(default_factory=list)
    severity_assessment: str | None = None
    confidence_score: float | None = None
    error: str | None = None
    latency_ms: float | None = None
    redaction_summary: dict[str, int] = Field(default_factory=dict)
    advisory_notice: str = (
        "ADVISORY ONLY: Output is generated by an untrusted AI model. "
        "Agni never automatically executes commands, alters firewalls, or kills processes."
    )


class AIModelListResponse(BaseModel):
    provider: str
    endpoint: str
    models: list[str] = Field(default_factory=list)
    status: str
    details: dict[str, Any] | None = None
